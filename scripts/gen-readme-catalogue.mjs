#!/usr/bin/env node
/**
 * The README's catalogue section — every tool, prompt, resource and resource
 * template — rendered from `catalogue.json`, the same dated snapshot API.md is
 * generated from.
 *
 *   node scripts/gen-readme-catalogue.mjs           # rewrite the section in README.md
 *   node scripts/gen-readme-catalogue.mjs --check   # fail if the section is not this output
 *
 * WHY GENERATED: the README is frozen inside a published tarball, so a catalogue
 * typed into it by hand starts rotting the first time a description changes on
 * the server. The section between the two markers below is therefore never
 * edited by hand; `--check` runs in CI. Every word in a row is the server's own
 * — the title its annotations carry and the FIRST sentence of its description —
 * except the group headings, which are ours and are the one hand-kept list here.
 *
 * PRECONDITIONS, each a refusal (exit 2), never a quiet success:
 *   - both markers present, once each, in order;
 *   - a catalogue with at least one tool, prompt and resource;
 *   - every tool placed in exactly ONE group, and every group naming only
 *     tools that exist: a new tool is a README change somebody has to make on purpose, and
 *     a retired one cannot linger under a heading.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BEGIN = '<!-- catalogue:begin — generated by scripts/gen-readme-catalogue.mjs from catalogue.json; do not edit by hand -->';
export const END = '<!-- catalogue:end -->';

/** Our grouping, by the question a traveller asks. The only hand-kept list in the section. */
export const GROUPS = [
  ['🚗 On the road', ['check_autobahn_traffic', 'check_road_status', 'find_roadworks_ahead', 'find_parking']],
  ['🚆 Public transport', ['get_train_departures', 'get_departures', 'check_transit_disruption', 'check_station_facilities']],
  ['⚡ Charging and fuel', ['find_charging_station', 'find_cheapest_fuel', 'find_fuel_station']],
  ['📍 Places and addresses', ['find_place', 'find_poi', 'find_address', 'describe_location', 'find_nearby']],
  ['🚲 Sharing', ['find_sharing']],
  ['🌦️ Weather and rules', ['check_weather_warnings', 'get_driving_rules']],
  ['🔔 Watches', ['watch_situation', 'stop_watch']],
];

const flat = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const cell = (s) => flat(s).replaceAll('|', String.raw`\|`);

/** The first sentence of a description: up to the first ". " (or the whole text). */
export function firstSentence(text) {
  const t = flat(text);
  // A full stop after an abbreviation does not end the sentence: find_sharing's
  // "(nextbike incl. KVB Rad, …)" was cut to "… (nextbike incl." in 1.8.18.
  for (const m of t.matchAll(/[.!?](?=\s|$)/g)) {
    const before = t.slice(0, m.index + 1);
    if (m[0] === '.' && ABBREVIATIONS.test(before)) continue;
    return before;
  }
  return t;
}

/** Abbreviations the server's descriptions use mid-sentence (English and German). */
const ABBREVIATIONS = /(?:^|[\s(])(?:incl|e\.g|i\.e|etc|ca|approx|vs|No|Nr|z|z\.\s?B|bzw|usw|ggf|inkl|St|Dr)\.$/u;

/** GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens. */
export function anchor(heading) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}

const toolTitle = (t) => t.annotations?.title ?? t.title ?? t.name;

export function renderSection(catalogue) {
  const tools = catalogue.tools ?? [];
  const prompts = catalogue.prompts ?? [];
  const resources = catalogue.resources ?? [];
  const templates = catalogue.resourceTemplates ?? [];
  if (tools.length === 0 || prompts.length === 0 || resources.length === 0)
    throw new Error(`the catalogue is incomplete (${tools.length} tools, ${prompts.length} prompts, ${resources.length} resources) — refusing to render a catalogue of nothing`);
  const byName = new Map(tools.map((t) => [t.name, t]));
  const grouped = GROUPS.flatMap(([, names]) => names);
  const unplaced = tools.map((t) => t.name).filter((n) => !grouped.includes(n));
  if (unplaced.length > 0) throw new Error(`tool(s) in no README group: ${unplaced.join(', ')} — add them to GROUPS on purpose`);
  const twice = grouped.filter((n, i) => grouped.indexOf(n) !== i);
  if (twice.length > 0) throw new Error(`tool(s) in more than one README group: ${[...new Set(twice)].join(', ')} — a tool is listed once`);
  const ghosts = grouped.filter((n) => !byName.has(n));
  if (ghosts.length > 0) throw new Error(`README group(s) name tool(s) the catalogue does not have: ${ghosts.join(', ')}`);

  const out = [BEGIN, ''];
  const version = catalogue.serverInfo?.version ?? '?';
  const day = String(catalogue.capturedAt ?? '').slice(0, 10);
  out.push(
    `**${tools.length} tools, ${prompts.length} prompts, ${resources.length} resources and ${templates.length} resource templates** — server ${version}, snapshot of ${day}. ` +
      'Each line is the server\'s own words; the full parameters are in [API.md](API.md).',
    '',
  );
  for (const [heading, names] of GROUPS) {
    out.push(`#### ${heading}`, '', '| tool | what it answers |', '|---|---|');
    for (const n of names) {
      const t = byName.get(n);
      const title = toolTitle(t);
      out.push(`| [\`${n}\`](API.md#${anchor(`\`${n}\` — ${title}`)}) — ${cell(title)} | ${cell(firstSentence(t.description))} |`);
    }
    out.push('');
  }
  out.push('#### 🧭 Prompts — ready-made briefings', '', 'Pick one in your client\'s prompt menu and fill in the blanks; it calls the right tools in the right order.', '', '| prompt | what it does |', '|---|---|');
  for (const p of prompts) out.push(`| \`${p.name}\` — ${cell(p.title ?? p.name)} | ${cell(firstSentence(p.description))} |`);
  out.push('', '#### 📚 Resources — reference your assistant can read', '', '| resource | what it holds |', '|---|---|');
  for (const r of resources) out.push(`| \`${r.uri}\` — ${cell(r.title ?? r.name)} | ${cell(firstSentence(r.description))} |`);
  for (const r of templates) out.push(`| \`${r.uriTemplate}\` — ${cell(r.title ?? r.name)} | ${cell(firstSentence(r.description))} |`);
  out.push('', END);
  return out.join('\n');
}

/** Replace the section between the markers; refuse when the markers are not exactly once each, in order. */
export function spliceReadme(readme, section) {
  const b = readme.indexOf(BEGIN);
  const e = readme.indexOf(END);
  if (b < 0 || e < 0 || e < b || readme.indexOf(BEGIN, b + 1) >= 0 || readme.indexOf(END, e + 1) >= 0)
    throw new Error('README.md must carry the catalogue markers exactly once each, begin before end');
  return readme.slice(0, b) + section + readme.slice(e + END.length);
}

function main(argv) {
  const readmePath = join(ROOT, 'README.md');
  let next;
  try {
    const catalogue = JSON.parse(readFileSync(join(ROOT, 'catalogue.json'), 'utf8'));
    next = spliceReadme(readFileSync(readmePath, 'utf8'), renderSection(catalogue));
  } catch (err) {
    console.error(`gen-readme-catalogue: could not render — ${err.message}`);
    return 2;
  }
  if (argv.includes('--check')) {
    if (readFileSync(readmePath, 'utf8') !== next) {
      console.error('gen-readme-catalogue: the README catalogue section is not what catalogue.json renders — run `npm run docs:readme`');
      return 1;
    }
    console.log('✓ README catalogue section matches catalogue.json');
    return 0;
  }
  writeFileSync(readmePath, next);
  console.log('README catalogue section written');
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exit(main(process.argv.slice(2)));
